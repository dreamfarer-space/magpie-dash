"""Agent avatars: the real logo of every coding agent magpie can wire up.

The SVGs in tools/agent_logos/ are the icons magpie itself shows for each agent
(LobeHub icon set, extracted from the magpie app). Each one is rendered at the
three sizes the dashboard draws, so the panel never has to scale a bitmap:

    S 20 px  list rows, route rows, topology chip
    M 56 px  home card, agent detail sheet
    L 88 px  state pages (think / code / confirm)

The agent ids are the keys magpie uses (~/.config/magpie/library.json
"applied", and the "agent" field of /v1/magpie/usage*).

Usage:  py -3.11 gen_agents.py            # preview PNG only
        py -3.11 gen_agents.py --write    # also write agent_sprites.h
Needs:  pip install resvg-py pillow
"""
import io
import os
import re
import sys

import resvg_py
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LOGOS = os.path.join(HERE, "agent_logos")
OUT = os.path.join(ROOT, "firmware", "magepie_dash", "agent_sprites.h")
PREVIEW = os.path.join(ROOT, "shots", "agents_preview.png")

MONO = "#F4F4F8"  # colour for single-colour (currentColor) logos on the dark UI
SIZES = (("s", 20), ("m", 56), ("l", 88))

# id, display name, accent colour (UI chrome), two lines the agent says when poked
# (ark12 glyphs: add new CJK to gen_fonts.py STRINGS)
AGENTS = [
    ("claude", "Claude Code", 0xD97757, "Clauding...", "这个文件交给我"),
    ("codex", "Codex", 0x7A8CFF, "> codex exec", "补丁已就绪"),
    ("grok", "Grok Build", 0xE8E8EE, "Grokking...", "让我想想宇宙的答案"),
    ("dsh", "DeepSeek Harness", 0x4D6BFE, "深度思考中", "鲸鱼出海"),
    ("hermes", "Hermes Agent", 0xE6C35C, "消息送达", "记住了，下次用"),
    ("pi", "Pi", 0xF4F4F8, "最小的 agent", "pi 正在运行"),
    ("zcode", "ZCode", 0x5B8CFF, "Z 已就位", "GLM 在线"),
    ("claude-desktop", "Claude Desktop", 0xD97757, "你好，我是 Claude", "桌面待命"),
    ("opencode", "OpenCode", 0xCFCFD8, "opencode run", "开源万岁"),
    ("cursor", "Cursor", 0xE8E8EE, "Tab Tab Tab", "已补全"),
    ("agy", "Antigravity", 0x3E8BFF, "起飞！", "反重力已开启"),
    ("codebuddy", "CodeBuddy", 0x7B5CFF, "喵~写好了", "摸鱼中"),
    ("commandcode", "Command Code", 0xE8E8EE, "命令已收到", "跑起来了"),
    ("mimocode", "MiMo Code", 0xFF6900, "MiMo 在线", "小米加步枪"),
    ("generic", "Agent", 0x8A8A99, "你好", "在这儿"),  # keep last: the fallback
]


def load_svg(aid):
    s = open(os.path.join(LOGOS, aid + ".svg"), encoding="utf-8").read()
    s = s.replace("currentColor", MONO)
    return re.sub(r'\s(width|height)="1em"', "", s)


def render(aid, size):
    """Logo fitted into a size x size transparent square (supersampled 4x)."""
    big = size * 4
    png = resvg_py.svg_to_bytes(svg_string=load_svg(aid), width=big, height=big)
    im = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
    if aid == "mimocode":
        # the Xiaomi MiMo mark is a two-line wordmark; keep its "MIMO" line
        a = im.getchannel("A")
        rows = [y for y in range(im.height) if a.crop((0, y, im.width, y + 1)).getbbox()]
        gaps = [rows[i] for i in range(1, len(rows)) if rows[i] - rows[i - 1] > 1]
        if gaps:
            im = im.crop((0, gaps[-1], im.width, im.height))
    im = im.crop(im.getbbox())
    pad = 0.92 if size > 24 else 1.0
    k = min(big * pad / im.width, big * pad / im.height)
    im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    sq = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    sq.paste(im, ((big - im.width) // 2, (big - im.height) // 2), im)
    return sq.resize((size, size), Image.LANCZOS)


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def preview():
    cell = 150
    sheet = Image.new("RGB", (cell * 5, 140 * ((len(AGENTS) + 4) // 5)), (21, 22, 29))
    for i, (aid, *_rest) in enumerate(AGENTS):
        x0, y0 = (i % 5) * cell, (i // 5) * 140
        ims = {k: render(aid, n) for k, n in SIZES}
        sheet.paste(ims["l"], (x0 + 8, y0 + 8), ims["l"])
        sheet.paste(ims["m"], (x0 + 100, y0 + 8), ims["m"])
        sheet.paste(ims["s"], (x0 + 110, y0 + 76), ims["s"])
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    sheet.save(PREVIEW)
    print("preview", PREVIEW)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write():
    out = ["// Generated by tools/gen_agents.py - do not edit", "#pragma once",
           "#include <lvgl.h>", ""]
    total = 0
    for aid, *_rest in AGENTS:
        for key, n in SIZES:
            im = render(aid, n)
            data = []
            for r, g, b, a in zip(*[iter(im.tobytes())] * 4):
                c = rgb565(r, g, b) if a else 0
                data += [c & 0xFF, c >> 8, a]  # RGB565 little endian + alpha
            total += len(data)
            sym = f"ag_{aid.replace('-', '_')}_{key}"
            out.append(f"static const uint8_t {sym}_map[] = {{{','.join(map(str, data))}}};")
            out.append(f"static const lv_img_dsc_t {sym} = {{{{LV_IMG_CF_TRUE_COLOR_ALPHA, 0, 0, {n}, {n}}}, "
                       f"{len(data)}, {sym}_map}};")
    out += [
        "",
        "struct AgentSkin {",
        "    const char *id;      // magpie agent id",
        "    const char *name;    // display name",
        "    uint32_t accent;     // UI accent colour",
        "    const lv_img_dsc_t *s, *m, *l;  // logo at 20 / 56 / 88 px",
        "    const char *say[2];  // what it says when poked",
        "};",
        "",
        "static const AgentSkin AGENT_SKINS[] = {",
    ]
    for aid, name, acc, say0, say1 in AGENTS:
        sym = "ag_" + aid.replace("-", "_")
        out.append(f'    {{"{aid}", {cstr(name)}, 0x{acc:06X}, &{sym}_s, &{sym}_m, &{sym}_l, '
                   f'{{{cstr(say0)}, {cstr(say1)}}}}},')
    out += ["};", f"#define AGENT_SKIN_COUNT {len(AGENTS)}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", OUT, f"{total // 1024} KB of pixels")


if __name__ == "__main__":
    preview()
    if "--write" in sys.argv:
        write()
